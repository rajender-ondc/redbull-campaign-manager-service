"use strict";

const { z } = require("zod");

// Request-validation building blocks that every resource's validator reuses (ADR-012). The fields
// and limits of each resource stay in its own validator.

const DEFAULT_PAGE_SIZE = 20;
const MAX_PAGE_SIZE = 100;

const PAGE_MESSAGE = "Must be a whole number of at least 1.";
const LIMIT_MESSAGE = `Must be a whole number from 1 to ${MAX_PAGE_SIZE}.`;
const BODY_MUST_BE_OBJECT = {
  error: "The request body must be a JSON object.",
};

/** The `:id` path parameter: a UUID the server generated. */
const idParamsSchema = z.strictObject({
  id: z.uuid({ error: "Must be a valid UUID." }),
});

// `If-Match: "3"` becomes expectedVersion 3. `*` (any version) and a missing header both leave
// expectedVersion undefined, meaning "don't check the version". Node gives header names in lowercase.
const ifMatchHeadersSchema = z
  .object({
    "if-match": z
      .string()
      .trim()
      .regex(/^(\*|"\d+")$/, {
        error: 'Must be "*" or an ETag from this API, such as "3".',
      })
      .optional(),
  })
  .transform(({ "if-match": ifMatch }) => ({
    expectedVersion:
      ifMatch === undefined || ifMatch === "*"
        ? undefined
        : Number(ifMatch.slice(1, -1)),
  }));

/** `?page=&limit=` on every list endpoint (ADR-010): page 1 and 20 items by default, at most 100. */
const paginationQuerySchema = z.strictObject({
  page: z.coerce
    .number({ error: PAGE_MESSAGE })
    .int({ error: PAGE_MESSAGE })
    .min(1, { error: PAGE_MESSAGE })
    .default(1),
  limit: z.coerce
    .number({ error: LIMIT_MESSAGE })
    .int({ error: LIMIT_MESSAGE })
    .min(1, { error: LIMIT_MESSAGE })
    .max(MAX_PAGE_SIZE, { error: LIMIT_MESSAGE })
    .default(DEFAULT_PAGE_SIZE),
});

/**
 * Builds the schema of a display name: a required string, trimmed, within a length range.
 * @param {{ minLength: number, maxLength: number }} lengthRange
 */
function buildNameSchema({ minLength, maxLength }) {
  const lengthMessage = `Must be ${minLength} to ${maxLength} characters.`;
  return z
    .string({
      error: (issue) =>
        issue.input === undefined ? "Required." : "Must be a string.",
    })
    .trim()
    .min(minLength, { error: lengthMessage })
    .max(maxLength, { error: lengthMessage });
}

/**
 * Builds the `?search=` query parameter of a list (ADR-010 §2): text to look for in the names.
 * It's trimmed, and a blank search means "no filter", so clearing the search box lists everything
 * again. A search longer than the longest possible name could never match, so it's rejected.
 * @param {{ maxLength: number }} limits The longest possible name of the resource.
 */
function buildSearchSchema({ maxLength }) {
  return z
    .string({ error: "Must be a single text value." })
    .trim()
    .max(maxLength, { error: `Must be at most ${maxLength} characters.` })
    .transform((text) => text || undefined)
    .optional();
}

/**
 * Builds a body schema with exactly these fields and no unknown ones, for bodies that aren't a
 * resource, such as a login. Mark the optional fields with `.optional()`.
 * @param {Record<string, import('zod').ZodType>} fields
 */
function buildBodySchema(fields) {
  return z.strictObject(fields, BODY_MUST_BE_OBJECT);
}

/**
 * Builds the body schema of a create (POST): these fields only. `id`, and any field listed in
 * `serverGeneratedFields` (such as an affiliate's `code`), are rejected because the server
 * generates them. Mark the optional fields with `.optional()`.
 * @param {Record<string, import('zod').ZodType>} fields
 * @param {{ serverGeneratedFields?: string[] }} [options]
 */
function buildCreateBodySchema(fields, { serverGeneratedFields = [] } = {}) {
  return buildBodySchema({
    ...buildRejectedFields(
      ["id", ...serverGeneratedFields],
      "is generated by the server.",
    ),
    ...fields,
  });
}

/**
 * Builds the body schema of a change (PATCH): any of these fields, at least one. `id`, and any field
 * listed in `immutableFields` (such as an affiliate's `code`), can never be changed. Every field
 * becomes optional, because PATCH changes only the fields sent.
 * @param {Record<string, import('zod').ZodType>} fields
 * @param {{ immutableFields?: string[] }} [options]
 */
function buildUpdateBodySchema(fields, { immutableFields = [] } = {}) {
  const optionalFields = Object.fromEntries(
    Object.entries(fields).map(([fieldName, fieldSchema]) => [
      fieldName,
      fieldSchema.optional(),
    ]),
  );
  return z
    .strictObject(
      {
        ...buildRejectedFields(
          ["id", ...immutableFields],
          "cannot be changed.",
        ),
        ...optionalFields,
      },
      BODY_MUST_BE_OBJECT,
    )
    .refine((body) => Object.keys(body).length > 0, {
      error: `Send at least one field to change: ${formatFieldList(Object.keys(fields))}.`,
    });
}

/** Builds optional fields that are always rejected with "<field> <reason>", e.g. "id cannot be changed.". */
function buildRejectedFields(fieldNames, reason) {
  return Object.fromEntries(
    fieldNames.map((fieldName) => [
      fieldName,
      z.never({ error: `${fieldName} ${reason}` }).optional(),
    ]),
  );
}

/** Formats field names as a list for a message: "name, defaultWindowDays or aliases". */
function formatFieldList(fieldNames) {
  if (fieldNames.length === 1) {
    return fieldNames[0];
  }
  return `${fieldNames.slice(0, -1).join(", ")} or ${fieldNames.at(-1)}`;
}

module.exports = {
  idParamsSchema,
  ifMatchHeadersSchema,
  paginationQuerySchema,
  buildNameSchema,
  buildSearchSchema,
  buildBodySchema,
  buildCreateBodySchema,
  buildUpdateBodySchema,
};
