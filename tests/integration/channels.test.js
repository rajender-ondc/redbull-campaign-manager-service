"use strict";

// API tests for the channel endpoints. They exercise the whole stack (routes → validator →
// controller → service → repository) against a real, throwaway, in-memory MongoDB.
// Behaviour channels share with categories through src/utils (malformed JSON, If-Match format,
// paging limits) is tested in depth in categories.test.js; here each shared path gets a smoke check.

const { describe, it, before, after, beforeEach } = require("node:test");
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const mongoose = require("mongoose");

const { createApp } = require("../../src/app");
const {
  startTestDatabase,
  clearTestDatabase,
  stopTestDatabase,
} = require("../setup/testDatabase");
const {
  UUID_PATTERN,
  assertProblem,
  getFieldErrors,
  sleep,
} = require("../setup/testHelpers");
const {
  createTestUser,
  createAuthorizedApi,
} = require("../setup/testAuth");

const BASE_URL = "/api/v1/channels";

const app = createApp();

before(startTestDatabase);
after(stopTestDatabase);
// Every request is sent by a signed-in admin (ADR-015); auth.test.js covers who may do what.
let adminAuthorization;
const api = createAuthorizedApi(app, () => adminAuthorization);

// Every test starts from empty collections, with a fresh admin, and creates the data it needs.
beforeEach(async () => {
  await clearTestDatabase();
  ({ authorization: adminAuthorization } = await createTestUser());
});

// ---------- helpers ----------

const postChannel = (body) => api.post(BASE_URL).send(body);

async function seedChannel(body) {
  const res = await postChannel(body);
  assert.equal(
    res.status,
    201,
    `test setup failed: ${JSON.stringify(res.body)}`,
  );
  return res.body.data;
}

const getChannelNames = (res) => res.body.data.map((channel) => channel.name);

/** Stores a campaign with one affiliate that places its links on the given channel. */
async function seedCampaignUsingChannel(channelId) {
  await mongoose.connection.collection("campaigns").insertOne({
    _id: new mongoose.mongo.UUID(),
    name: "Diwali Spices Sale",
    affiliates: [
      {
        affiliateId: new mongoose.mongo.UUID(),
        channelIds: [new mongoose.mongo.UUID(channelId)],
      },
    ],
  });
}

// ---------- tests ----------

describe("POST /api/v1/channels", () => {
  it("creates a channel: 201 with Location, ETag and the new channel", async () => {
    const res = await postChannel({ name: "  WhatsApp " });

    assert.equal(res.status, 201);
    const channel = res.body.data;
    assert.match(channel.id, UUID_PATTERN);
    assert.equal(res.headers.location, `${BASE_URL}/${channel.id}`);
    assert.equal(res.headers.etag, '"1"');
    assert.equal(channel.name, "WhatsApp");
    assert.equal(channel.currentVersionNo, 1);
    assert.ok(Date.parse(channel.createdAt));
    assert.ok(Date.parse(channel.updatedAt));
    assert.deepEqual(Object.keys(channel).sort(), [
      "createdAt",
      "currentVersionNo",
      "id",
      "name",
      "updatedAt",
    ]);
  });

  it("rejects a name that already exists in another letter case: 409 CHANNEL_NAME_TAKEN", async () => {
    await seedChannel({ name: "WhatsApp" });

    const res = await postChannel({ name: "WHATSAPP" });

    assertProblem(res, 409, "CHANNEL_NAME_TAKEN");
    assert.match(res.body.detail, /"WHATSAPP"/);
  });

  it("accepts a one-character name and rejects names that are empty or longer than 50 characters", async () => {
    await seedChannel({ name: "X" });

    for (const name of ["", "   ", "x".repeat(51)]) {
      const res = await postChannel({ name });

      assertProblem(res, 400, "VALIDATION_FAILED");
      assert.equal(getFieldErrors(res).name, "Must be 1 to 50 characters.");
    }
  });

  it("rejects a missing name, an id and unknown fields, listing each one", async () => {
    const res = await postChannel({
      id: randomUUID(),
      code: "wa",
      sortOrder: 1,
    });

    assertProblem(res, 400, "VALIDATION_FAILED");
    assert.deepEqual(getFieldErrors(res), {
      id: "id is generated by the server.",
      name: "Required.",
      code: "Unknown field.",
      sortOrder: "Unknown field.",
    });
  });

  it("rejects a body that is not JSON: 415 UNSUPPORTED_MEDIA_TYPE", async () => {
    const res = await api
      .post(BASE_URL)
      .set("Content-Type", "text/plain")
      .send("name=WhatsApp");

    assertProblem(res, 415, "UNSUPPORTED_MEDIA_TYPE");
  });
});

describe("GET /api/v1/channels", () => {
  it("lists channels sorted by name ignoring letter case, one page at a time", async () => {
    await seedChannel({ name: "WhatsApp" });
    await seedChannel({ name: "telegram" });
    await seedChannel({ name: "Instagram" });
    await seedChannel({ name: "Other" });

    const firstPage = await api.get(BASE_URL).query({ limit: 3 });
    const secondPage = await api
      .get(BASE_URL)
      .query({ page: 2, limit: 3 });

    assert.equal(firstPage.status, 200);
    assert.deepEqual(getChannelNames(firstPage), [
      "Instagram",
      "Other",
      "telegram",
    ]);
    assert.deepEqual(firstPage.body.pagination, {
      page: 1,
      limit: 3,
      totalItems: 4,
      totalPages: 2,
    });
    assert.deepEqual(getChannelNames(secondPage), ["WhatsApp"]);
  });

  it("rejects unknown query parameters", async () => {
    const res = await api.get(`${BASE_URL}?sort=name`);

    assertProblem(res, 400, "VALIDATION_FAILED");
  });
});

describe("GET /api/v1/channels?search=", () => {
  it("finds channels whose name contains the search text, ignoring letter case and outer spaces", async () => {
    for (const name of ["WhatsApp", "Telegram", "Instagram", "YouTube"]) {
      await seedChannel({ name });
    }

    const appResponse = await api
      .get(BASE_URL)
      .query({ search: "APP" });
    const gramResponse = await api
      .get(BASE_URL)
      .query({ search: " gram " });

    assert.equal(appResponse.status, 200);
    assert.deepEqual(getChannelNames(appResponse), ["WhatsApp"]);
    assert.deepEqual(getChannelNames(gramResponse), ["Instagram", "Telegram"]);
    assert.deepEqual(gramResponse.body.pagination, {
      page: 1,
      limit: 20,
      totalItems: 2,
      totalPages: 1,
    });
  });

  it("matches special characters in the search text exactly as typed", async () => {
    await seedChannel({ name: "Website / blog" });
    await seedChannel({ name: "C++ forum" });
    await seedChannel({ name: "Other" });

    const slashResponse = await api
      .get(BASE_URL)
      .query({ search: "/" });
    const plusResponse = await api
      .get(BASE_URL)
      .query({ search: "c++" });
    // ".*" is plain text here, not a pattern that matches everything.
    const patternResponse = await api
      .get(BASE_URL)
      .query({ search: ".*" });

    assert.deepEqual(getChannelNames(slashResponse), ["Website / blog"]);
    assert.deepEqual(getChannelNames(plusResponse), ["C++ forum"]);
    assert.deepEqual(getChannelNames(patternResponse), []);
  });

  it("pages through the matches and counts only the matches", async () => {
    for (const name of [
      "Telegram",
      "Instagram",
      "Telegram channels",
      "Other",
    ]) {
      await seedChannel({ name });
    }

    const res = await api
      .get(BASE_URL)
      .query({ search: "gram", page: 2, limit: 2 });

    assert.deepEqual(getChannelNames(res), ["Telegram channels"]);
    assert.deepEqual(res.body.pagination, {
      page: 2,
      limit: 2,
      totalItems: 3,
      totalPages: 2,
    });
  });

  it("lists every channel for a blank search, and returns an empty page when nothing matches", async () => {
    await seedChannel({ name: "WhatsApp" });
    await seedChannel({ name: "Telegram" });

    const blankResponse = await api.get(`${BASE_URL}?search=%20%20`);
    const noMatchResponse = await api
      .get(BASE_URL)
      .query({ search: "LinkedIn" });

    assert.deepEqual(getChannelNames(blankResponse), ["Telegram", "WhatsApp"]);
    assert.equal(noMatchResponse.status, 200);
    assert.deepEqual(getChannelNames(noMatchResponse), []);
    assert.deepEqual(noMatchResponse.body.pagination, {
      page: 1,
      limit: 20,
      totalItems: 0,
      totalPages: 0,
    });
  });

  it("rejects a search longer than 50 characters, or sent twice", async () => {
    const tooLongResponse = await api
      .get(BASE_URL)
      .query({ search: "x".repeat(51) });
    const twiceResponse = await api.get(
      `${BASE_URL}?search=whats&search=app`,
    );

    assertProblem(tooLongResponse, 400, "VALIDATION_FAILED");
    assert.equal(
      getFieldErrors(tooLongResponse).search,
      "Must be at most 50 characters.",
    );
    assertProblem(twiceResponse, 400, "VALIDATION_FAILED");
    assert.equal(
      getFieldErrors(twiceResponse).search,
      "Must be a single text value.",
    );
  });
});

describe("GET /api/v1/channels/:id", () => {
  it("returns the channel with its ETag", async () => {
    const createdChannel = await seedChannel({ name: "Telegram" });

    const res = await api.get(`${BASE_URL}/${createdChannel.id}`);

    assert.equal(res.status, 200);
    assert.equal(res.headers.etag, '"1"');
    assert.deepEqual(res.body.data, createdChannel);
  });

  it("returns 404 CHANNEL_NOT_FOUND for an unknown id", async () => {
    const res = await api.get(`${BASE_URL}/${randomUUID()}`);

    assertProblem(res, 404, "CHANNEL_NOT_FOUND");
  });

  it("returns 400 for an id that is not a UUID", async () => {
    const res = await api.get(`${BASE_URL}/not-a-uuid`);

    assertProblem(res, 400, "VALIDATION_FAILED");
    assert.equal(getFieldErrors(res).id, "Must be a valid UUID.");
  });
});

describe("PATCH /api/v1/channels/:id", () => {
  it("renames a channel, keeps its id and increases the version", async () => {
    const createdChannel = await seedChannel({ name: "Telgram" }); // misspelt
    await sleep(10);

    const res = await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .send({ name: "Telegram" });

    assert.equal(res.status, 200);
    assert.equal(res.headers.etag, '"2"');
    const updatedChannel = res.body.data;
    assert.equal(updatedChannel.id, createdChannel.id);
    assert.equal(updatedChannel.name, "Telegram");
    assert.equal(updatedChannel.currentVersionNo, 2);
    assert.equal(updatedChannel.createdAt, createdChannel.createdAt);
    assert.ok(
      Date.parse(updatedChannel.updatedAt) >
        Date.parse(createdChannel.updatedAt),
    );
  });

  it("refuses a stale If-Match with 412 VERSION_MISMATCH and changes nothing", async () => {
    const createdChannel = await seedChannel({ name: "Website" });
    await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .send({ name: "Website / blog" }); // now version 2

    const res = await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .set("If-Match", '"1"')
      .send({ name: "Blog" });

    assertProblem(res, 412, "VERSION_MISMATCH");
    const currentResponse = await api.get(
      `${BASE_URL}/${createdChannel.id}`,
    );
    assert.equal(currentResponse.body.data.name, "Website / blog");
    assert.equal(currentResponse.body.data.currentVersionNo, 2);
  });

  it("applies the change when If-Match has the current version", async () => {
    const createdChannel = await seedChannel({ name: "Website" });

    const res = await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .set("If-Match", '"1"')
      .send({ name: "Website / blog" });

    assert.equal(res.status, 200);
    assert.equal(res.body.data.name, "Website / blog");
  });

  it("rejects a name another channel already has: 409 CHANNEL_NAME_TAKEN", async () => {
    await seedChannel({ name: "WhatsApp" });
    const telegramChannel = await seedChannel({ name: "Telegram" });

    const res = await api
      .patch(`${BASE_URL}/${telegramChannel.id}`)
      .send({ name: "whatsapp" });

    assertProblem(res, 409, "CHANNEL_NAME_TAKEN");
  });

  it("rejects an empty body, naming the field that can change", async () => {
    const createdChannel = await seedChannel({ name: "WhatsApp" });

    const res = await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .send({});

    assertProblem(res, 400, "VALIDATION_FAILED");
    assert.equal(
      getFieldErrors(res).body,
      "Send at least one field to change: name.",
    );
  });

  it("returns 404 CHANNEL_NOT_FOUND for an unknown channel", async () => {
    const res = await api
      .patch(`${BASE_URL}/${randomUUID()}`)
      .send({ name: "Telegram" });

    assertProblem(res, 404, "CHANNEL_NOT_FOUND");
  });
});

describe("DELETE /api/v1/channels/:id", () => {
  it("deletes an unused channel: 204, then the channel is gone", async () => {
    const createdChannel = await seedChannel({ name: "Facebook" });

    const res = await api.delete(`${BASE_URL}/${createdChannel.id}`);

    assert.equal(res.status, 204);
    assert.equal(res.text, "");
    assertProblem(
      await api.get(`${BASE_URL}/${createdChannel.id}`),
      404,
      "CHANNEL_NOT_FOUND",
    );
  });

  it("refuses to delete a channel a campaign's affiliate uses: 409 CHANNEL_IN_USE", async () => {
    const usedChannel = await seedChannel({ name: "WhatsApp" });
    const unusedChannel = await seedChannel({ name: "YouTube" });
    await seedCampaignUsingChannel(usedChannel.id);

    const usedResponse = await api.delete(
      `${BASE_URL}/${usedChannel.id}`,
    );
    const unusedResponse = await api.delete(
      `${BASE_URL}/${unusedChannel.id}`,
    );

    assertProblem(usedResponse, 409, "CHANNEL_IN_USE");
    assert.match(usedResponse.body.detail, /"WhatsApp"/);
    assert.equal(
      (await api.get(`${BASE_URL}/${usedChannel.id}`)).status,
      200,
    );
    assert.equal(unusedResponse.status, 204);
  });

  it("refuses a stale If-Match with 412 and keeps the channel", async () => {
    const createdChannel = await seedChannel({ name: "Website" });
    await api
      .patch(`${BASE_URL}/${createdChannel.id}`)
      .send({ name: "Website / blog" }); // now version 2

    const res = await api
      .delete(`${BASE_URL}/${createdChannel.id}`)
      .set("If-Match", '"1"');

    assertProblem(res, 412, "VERSION_MISMATCH");
    assert.equal(
      (await api.get(`${BASE_URL}/${createdChannel.id}`)).status,
      200,
    );
  });
});

describe("Unsupported requests", () => {
  it("returns 405 METHOD_NOT_ALLOWED with an Allow header", async () => {
    const createdChannel = await seedChannel({ name: "WhatsApp" });

    const putResponse = await api
      .put(`${BASE_URL}/${createdChannel.id}`)
      .send({ name: "Telegram" });
    const deleteCollectionResponse = await api.delete(BASE_URL);

    assertProblem(putResponse, 405, "METHOD_NOT_ALLOWED");
    assert.equal(putResponse.headers.allow, "GET, PATCH, DELETE");
    assertProblem(deleteCollectionResponse, 405, "METHOD_NOT_ALLOWED");
    assert.equal(deleteCollectionResponse.headers.allow, "GET, POST");
  });
});
